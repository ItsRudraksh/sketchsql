@app.get("/api/")
async def health():
    return {"message": "SketchSQL API running", "status": "ok"}

@app.post("/api/generate-sql")
async def generate_sql_route(req: GenerateSqlRequest):
    try:
        sql = generate_mysql(req.diagram) if req.dialect == "mysql" else generate_postgresql(req.diagram)
        return {"sql": sql}
    except Exception as e:
        raise HTTPException(status_code=500, detail=str(e))

@app.post("/api/import-sql")
async def import_sql_route(req: ImportSqlRequest):
    try:
        return {"diagram": parse_sql(req.sql, req.dialect)}
    except Exception as e:
        raise HTTPException(status_code=500, detail=str(e))

@app.post("/api/ai/generate-schema")
async def ai_generate_schema(req: AiGenerateSchemaRequest):
    try:
        system_prompt = """You are a database schema designer. The user will describe a system in plain English.
You must respond ONLY with a valid JSON object representing a database schema.
No explanation, no markdown, no backticks. Only raw JSON.

The JSON must follow this exact schema:
{
  "tables": [
    {
      "id": "unique_string_id",
      "name": "TableName",
      "color": "blue|green|purple|orange|red|gray",
      "columns": [
        {
          "id": "unique_col_id",
          "name": "column_name",
          "type": "INT|VARCHAR(255)|TEXT|BOOLEAN|DATE|DATETIME|TIMESTAMP|DECIMAL(10,2)|UUID|BIGINT|FLOAT|JSON",
          "primaryKey": true,
          "autoIncrement": true,
          "nullable": false,
          "unique": false,
          "defaultValue": ""
        }
      ]
    }
  ],
  "relationships": [
    {
      "id": "unique_rel_id",
      "sourceTableId": "id",
      "sourceColumnId": "id",
      "targetTableId": "id",
      "targetColumnId": "id",
      "type": "one-to-one|one-to-many|many-to-many",
      "onDelete": "CASCADE|SET NULL|RESTRICT",
      "onUpdate": "CASCADE|SET NULL|RESTRICT"
    }
  ]
}"""
        resp = get_client().chat.completions.create(
            model=DEPLOYMENT(),
            messages=[
                {"role": "system", "content": system_prompt},
                {"role": "user", "content": f"Design a database schema for: {req.prompt}"},
            ],
            max_completion_tokens=16384,
        )
        content = resp.choices[0].message.content.strip()
        content = re.sub(r"^```[a-z]*\n?", "", content)
        content = re.sub(r"\n?```$", "", content)
        diagram = json.loads(content)
        return {"diagram": diagram}
    except json.JSONDecodeError as e:
        raise HTTPException(status_code=422, detail=f"AI returned invalid JSON: {e}")
    except Exception as e:
        raise HTTPException(status_code=500, detail=str(e))

